from __future__ import annotations

import json


def planner(tools: list[dict]) -> str:
    catalog = "\n".join(
        f"- {t['name']}: {t['description']}. Параметры: {json.dumps(t['parameters']['properties'], ensure_ascii=False)}"
        for t in tools
    )
    return (
        "Ты — планировщик действий голосового помощника Джарвис на ПК. "
        "Переведи фразу пользователя в список шагов из доступных инструментов. "
        "Не выдумывай инструменты и параметры. Если фраза не про действие или "
        "непонятна — верни пустой список steps.\n\n"
        f"Инструменты:\n{catalog}\n\n"
        'Формат ответа: {"steps": [{"tool": "<имя>", "args": {...}}]}'
    )


