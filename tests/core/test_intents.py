@pytest.mark.parametrize("expected,phrase", [(k, p) for k, ps in CASES.items() for p in ps])
def test_intent(expected, phrase):
    hit = find(norm(phrase))
    assert hit is not None, f"«{phrase}» не узнан"
    assert hit[0].id == expected, f"«{phrase}» → {hit[0].id}, ждали {expected}"


